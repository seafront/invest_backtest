/**
 * 상태 색상 토큰.
 *
 * 하드코딩된 hex가 파일마다 흩어지면 같은 의미에 다른 색이 쓰이기 쉽다.
 * 실제로 "상승"을 뜻하는 녹색이 #22c55e와 #10b981 두 가지로 갈렸던 적이 있다.
 *
 * POSITIVE/NEGATIVE 조합은 색각이상 검증을 통과한 값이다 (deutan ΔE 8.1).
 * 다크 배경(#1e1e2e) 기준으로 고른 값이므로 임의로 바꾸지 말 것.
 * 부호는 색뿐 아니라 위치·기호로도 함께 표현해 색만으로 구분되지 않게 한다.
 */
