export const CAUTION = "#eab308"; // 보통 — 좋지도 나쁘지도 않은 중간 구간

/**
 * 지표 오버레이용 계열 색상.
 * 캔들의 POSITIVE/NEGATIVE와 색상 계열이 겹치지 않는다.
 * 녹색 계열은 넣지 않는다 — 상승 캔들과 일반 시야에서도 구분되지 않았다.
 *
 * 원래 4색이었다. "지표를 3개 넘게 내보내는 전략이 없다"는 전제였는데, 산업 비교
 * 화면이 한 차트에 6종목을 그리면서 5번째부터 색이 되돌아왔다 — 삼성전자와 SanDisk가
 * 같은 주황으로 겹쳤다. 그래서 두 색을 더했다.
 *
 * 추가한 두 색은 눈대중이 아니라 재서 골랐다. Viénot(1999) 방식으로 deutan·protan을
 * 시뮬레이션한 뒤 CIELAB ΔE76 최소값을 비교했고, 후보 12색의 모든 쌍 중 이 조합이
 * 가장 높았다:
 *
 *   4색 기준  일반 64.5 · deutan 31.5 · protan 11.7
 *   6색 결과  일반 42.1 · deutan 29.4 · protan 11.7
 *
 * deutan이 조금 낮아졌지만 protan은 그대로다 — protan의 11.7은 새 색 때문이 아니라
 * 원래 4색 안에 있던 한계다. 색을 더 늘릴 일이 있으면 같은 방법으로 재고 이 표를 갱신할 것.
 */
